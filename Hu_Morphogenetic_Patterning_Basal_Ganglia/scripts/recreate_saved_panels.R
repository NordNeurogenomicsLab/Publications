suppressPackageStartupMessages(library(Seurat))
suppressPackageStartupMessages(library(ggplot2))
suppressPackageStartupMessages(library(patchwork))
w <- Sys.getenv('JIA_WORK_DIR', unset='/mnt/disks/data1/Jia_GEO_submission/codex_review')
out<-file.path(w,'figures');dir.create(out,showWarnings=FALSE)
saveplot<-function(p,n,width=6,height=4.5)ggsave(file.path(out,paste0(n,'.png')),p,width=width,height=height,dpi=220,bg='white')
x<-readRDS(file.path(w,'inputs/seurat_objects/MGE_1538_E11_and_E13_with_new_E13.Rds'))
cat('INTEGRATED\n');print(validObject(x));print(x@version);print(table(x$age));print(table(x$Dev_classes));print(DefaultAssay(x));print(mean(x$nFeature_RNA))
write.csv(x@meta.data,file.path(w,'audit/integrated_metadata.csv'))
write.csv(Embeddings(x,'umap'),file.path(w,'audit/integrated_umap.csv'))
saveplot(DimPlot(x,group.by='age',cols=c(E11='#F8766D',E13='#00BFC4')),'Fig3A_age')
DefaultAssay(x)<-'SCT'
for(g in c('Hes1','Ascl1','Dcx'))saveplot(FeaturePlot(x,features=g,cols=c('lightgrey','#7561A8')),paste0('Fig3A_',g))
vz<-subset(x,cells=rownames(x@meta.data)[x$Dev_classes=='VZ'])
for(g in c('Id4','Mest','Dlx2','Nfib'))saveplot(FeaturePlot(vz,features=g,split.by='age',cols=c('lightgrey','#7561A8')),paste0('Fig3_split_',g),10,4)
cat('MZ\n')
m<-readRDS(file.path(w,'inputs/seurat_objects/MZ_reintegrated_on_52_PN_genes_08_15_2025.rds'))
print(validObject(m));print(dim(m));print(table(m$age));print(names(m@meta.data));print(names(m@reductions));print(DefaultAssay(m)); print(mean(m$nFeature_RNA))
write.csv(m@meta.data,file.path(w,'audit/MZ_metadata.csv'))
write.csv(Embeddings(m,'umap'),file.path(w,'audit/MZ_umap.csv'))
saveplot(DimPlot(m,group.by='age',cols=c(E11='#00BFC4',E13='#F8766D')),'Fig4D_age')
saveplot(DimPlot(m,label=TRUE),'Fig4D_clusters')
DefaultAssay(m)<-'SCT'
for(g in c('Lhx8','Mest','Npy','Mafb'))saveplot(FeaturePlot(m,features=g,split.by='age',cols=c('lightgrey','#7561A8')),paste0('Fig4_split_',g),10,4)
d<-as.data.frame(table(cluster=m$seurat_clusters,age=m$age));d$percent<-100*d$Freq/ave(d$Freq,d$age,FUN=sum)
write.csv(d,file.path(w,'audit/MZ_cluster_age_proportions.csv'),row.names=FALSE)
saveplot(ggplot(d,aes(cluster,percent,fill=age))+geom_col()+scale_fill_manual(values=c(E11='#00BFC4',E13='#F8766D'))+theme_classic()+labs(y='Percent of cells within age',x='Stored cluster'),'Fig4D_cluster_proportions',9,4)
